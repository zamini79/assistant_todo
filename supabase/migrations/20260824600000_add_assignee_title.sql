-- 담당자 직책
--
-- 사원 명부를 쓰면서 담당자의 이름·부서·이메일을 값으로 복사해 두는데, 직책이 빠져 있었다.
-- Remind 메일이 "이름 직책님"으로 인사해야 해서 함께 복사한다.
--
-- 명부를 참조하지 않고 복사하는 이유는 다른 필드와 같다 —
-- 인사정보 연동 시 명부를 비워도, 직책이 바뀌어도, 그때 보낸 메일의 호칭은 남아야 한다.
--
-- 옛 데이터는 빈 문자열이다. 이름 안에 직책이 이미 섞여 있는 경우가 있어
-- (예: "홍길동 실장") 기계적으로 쪼개지 않는다 — 잘못 쪼개면 호칭이 어색해진다.
-- 그 건들은 이름만으로 인사하고, 담당자를 다시 고르면 직책이 채워진다.

alter table public.todos
  add column if not exists assignee_title text not null default '';

comment on column public.todos.assignee_title is
  '담당자 직책. 사원 명부에서 복사한 값. 옛 데이터는 비어 있고, 그 경우 이름만으로 호칭한다.';
